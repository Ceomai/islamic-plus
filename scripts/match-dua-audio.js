/**
 * Maps app duas to per-dua MP3 URLs from Alsarmad/Adhkar-json (Hisnul Muslim audio).
 * Run: node scripts/match-dua-audio.js
 */
const fs = require('fs');
const path = require('path');
const https = require('https');

const AUDIO_BASE = 'https://cdn.jsdelivr.net/gh/Alsarmad/Adhkar-json@main';
const ADHKAR_URL = `${AUDIO_BASE}/adhkar.json`;

const DUAS = [
  { id: 'morning-1', needle: 'أَصْبَحْنَا' },
  { id: 'evening-1', needle: 'أَمْسَيْنَا' },
  { id: 'before-food', needle: 'اللَّهُمَّ بَارِكْ', alt: 'بِسْمِ اللَّهِ وَعَلَى' },
  { id: 'after-food', needle: 'أَطْعَمَنَا' },
  { id: 'enter-mosque', needle: 'أَبْوَابَ رَحْمَتِكَ' },
  { id: 'travel', needle: 'سَخَّرَ لَنَا', alt: 'سخر لنا' },
  { id: 'istighfar', needle: 'أَسْتَغْفِرُ', alt: 'استغفر' },
  { id: 'sleep', needle: 'أَمُوتُ وَأَحْيَا' },
];

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        let data = '';
        res.on('data', (c) => (data += c));
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(e);
          }
        });
      })
      .on('error', reject);
  });
}

function normalizeArabic(s) {
  return (s || '')
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[ٱأإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

const MANUAL_FALLBACK = {
  'before-food': '/audio/178.mp3',
  'travel': '/audio/207.mp3',
  'istighfar': '/audio/250.mp3',
};

function toUrl(rel) {
  if (!rel) return null;
  return `${AUDIO_BASE}${rel.startsWith('/') ? rel : '/' + rel}`;
}

function findAudio(categories, needle, short, alt) {
  const needles = [needle, alt].filter(Boolean).map(normalizeArabic);
  for (const n of needles) {
    for (const cat of categories) {
      for (const item of cat.array || []) {
        const text = normalizeArabic(item.text || '');
        if (n && text.includes(n)) {
          if (short && text.length > 80) continue;
          const url = toUrl(item.audio);
          if (url) return url;
        }
      }
    }
  }
  return null;
}

async function main() {
  const categories = await fetchJson(ADHKAR_URL);
  const map = {};
  for (const dua of DUAS) {
    map[dua.id] =
      findAudio(categories, dua.needle, dua.short, dua.alt) ||
      toUrl(MANUAL_FALLBACK[dua.id]) ||
      null;
  }
  const out = `/** Auto-generated by scripts/match-dua-audio.js — Hisnul Muslim (Alsarmad/Adhkar-json) */\nexport const DUA_AUDIO_URLS: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
  const dest = path.join(__dirname, '..', 'src', 'data', 'duaAudioUrls.ts');
  fs.writeFileSync(dest, out);
  console.log('Written', dest);
  for (const [id, url] of Object.entries(map)) {
    console.log(id, url ? 'OK' : 'MISSING');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
